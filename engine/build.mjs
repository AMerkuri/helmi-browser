// npm run build: everything the app needs from the engine besides src/content/serene.js.
//   dist/autoconsent.js          DuckDuckGo autoconsent + src/content/autoconsent-entry.js
//   dist/autoconsent-rules.json  its compact rule set (the app filters it per frame URL)
//   dist/autoconsent-config.json the config the host sends with the rules (src/host/autoconsent.mjs)
//   dist/reader.js               Mozilla Readability + src/content/reader-entry.js (reader mode)
//   dist/scriptlets.json         uBlock Origin's scriptlets and stand-in files as adblock-rust resources
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import * as acorn from 'acorn';
import adblock from 'adblock-rs';
import { createRequire } from 'node:module';
import { build } from 'esbuild';
import { filterCompactRules, decodeRules } from '@duckduckgo/autoconsent';
import { AUTOCONSENT_CONFIG } from './src/host/autoconsent.mjs';
import { TRUSTED } from './src/host/lists.mjs';

const require = createRequire(import.meta.url);
const out = new URL('./dist/', import.meta.url).pathname;
fs.mkdirSync(out, { recursive: true });
const compact = require('@duckduckgo/autoconsent/rules/compact-rules.json');

// What autoconsent prehides on any top-level page: the containers of the consent tools it has
// generic rules for. Its own prehide starts only once the host's init reply arrives, and a site
// that renders its banner in the HTML (Stack Overflow in the EU) shows it until then, so the
// bundle hides the same containers from document start (src/content/autoconsent-entry.js).
async function earlyPrehideSelectors() {
  // The coded rules (OneTrust, Cookiebot, TrustArc, ...) only exist on an AutoConsent instance,
  // which needs a window to construct; nothing else of the page is touched.
  const page = { location: { href: 'https://example.invalid/' } };
  Object.assign(globalThis, { window: page, location: page.location });
  page.top = page;
  const { default: AutoConsent } = await import('@duckduckgo/autoconsent');
  const coded = new AutoConsent(() => Promise.resolve()).rules;
  delete globalThis.window; delete globalThis.location;
  const declarative = decodeRules(filterCompactRules(compact, { url: 'https://example.invalid/', mainFrame: true }));
  const sels = new Set();
  for (const r of [...coded, ...declarative]) {
    if (r.runContext && (r.runContext.main === false || r.runContext.urlPattern)) continue;
    for (const s of r.prehideSelectors || []) sels.add(s);
  }
  return [...sels];
}
const prehide = AUTOCONSENT_CONFIG.enablePrehide ? await earlyPrehideSelectors() : [];

const { version } = JSON.parse(fs.readFileSync(new URL('./node_modules/@duckduckgo/autoconsent/package.json', import.meta.url), 'utf8'));
await build({
  entryPoints: ['src/content/autoconsent-entry.js'],
  bundle: true,
  format: 'iife',
  minify: true,
  outfile: out + 'autoconsent.js',
  define: { __SERENE_EARLY_PREHIDE__: JSON.stringify(prehide.join(',')) },
  banner: { js: `// Generated by 'npm run build' from src/content/autoconsent-entry.js. Bundles @duckduckgo/autoconsent ${version} (MPL-2.0, https://github.com/duckduckgo/autoconsent).` },
});
fs.copyFileSync(require.resolve('@duckduckgo/autoconsent/rules/compact-rules.json'), out + 'autoconsent-rules.json');
fs.writeFileSync(out + 'autoconsent-config.json', JSON.stringify(AUTOCONSENT_CONFIG, null, 1) + '\n');
const readability = JSON.parse(fs.readFileSync(new URL('./node_modules/@mozilla/readability/package.json', import.meta.url), 'utf8')).version;
await build({
  entryPoints: ['src/content/reader-entry.js'],
  bundle: true,
  format: 'iife',
  minify: true,
  outfile: out + 'reader.js',
  banner: { js: `// Generated by 'npm run build' from src/content/reader-entry.js. Bundles @mozilla/readability ${readability} (Apache-2.0, https://github.com/mozilla/readability).` },
});

// uBO's scriptlets (set-constant, trusted-click-element, ...), which the lists' `##+js(...)` rules
// name. uBO keeps them as ES modules in src/js/resources, each a function registered with
// `registerScriptlet(fn, { name, aliases, dependencies, requiresTrust })`. They are read
// statically (parsed, never run here) and turned into function-style adblock-rust resources: the
// body is the function's source and the rule's arguments become call arguments, the same
// conversion Brave does. Scriptlets uBO marks `requiresTrust` get the TRUSTED permission bit, so
// only lists parsed as trusted (uBO's own) can inject them.
// Pinned: lists name scriptlets that exist in uBO's current release; bump with uBO stable.
const UBO_VERSION = '1.75.0';
function uboScriptlets() {
  const dir = new URL(`./.cache/ublock-${UBO_VERSION}/`, import.meta.url).pathname;
  const resDir = dir + 'src/js/resources/';
  const warDir = dir + 'src/web_accessible_resources/';
  if (!fs.existsSync(resDir + 'scriptlets.js') || !fs.existsSync(warDir)) {
    fs.rmSync(dir, { recursive: true, force: true });
    fs.mkdirSync(dir, { recursive: true });
    const git = (...a) => execFileSync('git', a, { cwd: dir, stdio: 'ignore' });
    git('init', '-q');
    git('remote', 'add', 'origin', 'https://github.com/gorhill/uBlock.git');
    git('sparse-checkout', 'set', '--no-cone', '/src/js/', '/src/web_accessible_resources/');
    git('fetch', '-q', '--depth', '1', '--filter=blob:none', 'origin', `refs/tags/${UBO_VERSION}`);
    git('checkout', '-q', 'FETCH_HEAD');
  }
  const fns = new Map(); // function or class name -> source
  const regs = []; // [function name (or null: the details' fn), details node, file]
  // The resources, plus the helpers they import from src/js (urlskip.js, jsonpath.js, ...).
  const files = fs.readdirSync(resDir).filter((f) => f.endsWith('.js')).sort().map((f) => resDir + f);
  for (let i = 0; i < files.length; i++) {
    const file = files[i], src = fs.readFileSync(file, 'utf8');
    for (const node of acorn.parse(src, { ecmaVersion: 'latest', sourceType: 'module' }).body) {
      if (node.type === 'ImportDeclaration') {
        const dep = new URL(node.source.value, 'file://' + file).pathname;
        if (!files.includes(dep)) files.push(dep);
      }
      const decl = node.type === 'ExportNamedDeclaration' ? node.declaration : node;
      if (decl?.type === 'FunctionDeclaration' || decl?.type === 'ClassDeclaration') fns.set(decl.id.name, src.slice(decl.start, decl.end));
      // registerScriptlet(fn, { name, ... }) or, in scriptlets.js, builtinScriptlets.push({ name, fn, ... }).
      const call = node.type === 'ExpressionStatement' && node.expression.type === 'CallExpression' ? node.expression : null;
      if (call?.callee.name === 'registerScriptlet') regs.push([call.arguments[0].name, call.arguments[1], path.basename(file)]);
      if (call?.callee.object?.name === 'builtinScriptlets' && call.callee.property.name === 'push') regs.push([null, call.arguments[0], path.basename(file)]);
    }
  }
  // Details are plain literals; dependencies name other registered functions.
  const value = (n, file) => {
    if (n.type === 'Literal') return n.value;
    if (n.type === 'ArrayExpression') return n.elements.map((e) => value(e, file));
    if (n.type === 'Identifier') return { fn: n.name };
    throw new Error(`${file}: unexpected ${n.type} in scriptlet details`);
  };
  const details = regs.map(([fn, obj, file]) => {
    const d = Object.fromEntries(obj.properties.map((p) => [p.key.name ?? p.key.value, value(p.value, file)]));
    d.fn = fn ?? d.fn?.fn;
    if (!fns.has(d.fn)) throw new Error(`${file}: no function ${d.fn} for ${d.name}`);
    return d;
  });
  const nameOf = new Map(details.map((d) => [d.fn, d.name]));
  // uBO's stand-in files (noeval.js, nofab.js, noop.js, ...), which rules also inject with +js().
  // adblock-rust reads them and redirect-resources.js itself. Brave leaves out google-ima-dai.js too.
  const war = adblock.uBlockResources(warDir, dir + 'src/js/redirect-resources.js').filter((r) => r.name !== 'google-ima-dai.js');
  return [...war, ...details.map((d) => ({
    name: d.name,
    aliases: d.aliases ?? [],
    kind: { mime: 'application/javascript' },
    content: Buffer.from(fns.get(d.fn)).toString('base64'),
    ...(d.dependencies?.length ? {
      dependencies: d.dependencies.map((x) => {
        const n = typeof x === 'string' ? x : nameOf.get(x.fn);
        if (!n) throw new Error(`${d.name}: dependency ${x.fn} is not a registered scriptlet`);
        return n;
      }),
    } : {}),
    ...(d.requiresTrust ? { permission: TRUSTED } : {}),
  }))];
}
const scriptlets = uboScriptlets();
fs.writeFileSync(out + 'scriptlets.json', JSON.stringify({
  source: `uBlock Origin ${UBO_VERSION} src/js/resources (GPL-3.0, https://github.com/gorhill/uBlock), built by 'npm run build'`,
  resources: scriptlets,
}) + '\n');
console.log(`dist/: scriptlets.json (uBO ${UBO_VERSION}, ${scriptlets.length} resources, ${scriptlets.filter((s) => s.permission).length} trusted-only)`);
console.log(`dist/: reader.js (readability ${readability})`);
console.log(`dist/: autoconsent ${version} (${prehide.length} early prehide selectors), rules and config written`);
